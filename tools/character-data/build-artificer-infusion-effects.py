"""Curated, localized play summaries of TCE infusion rules from the pinned reference."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[2]
rows=[line.split('\t') for line in Path(__file__).with_name('artificer-infusion-effects.tsv').read_text(encoding='utf-8').splitlines() if line]
assert all(len(row)==4 for row in rows)
quote=lambda v:json.dumps(v,ensure_ascii=False)
lines=['// Generated by tools/character-data/build-artificer-infusion-effects.py.',
       'namespace Taruck.CharacterCreation {',
       '    public static class CharacterArtificerInfusionEffects {',
       '        public static string Get(string id) { switch(id) {']
lines+=['            case '+quote(key)+': return '+quote(ua)+';' for key,ua,_,_ in rows]
lines+=['            default: return "";', '        } }','    }','}']
(root/'Assets/Skripts/Domain/CharacterArtificerInfusionEffects.cs').write_text('\n'.join(lines)+'\n',encoding='utf-8')
path=root/'Assets/Resources/Localization.txt'
text=path.read_text(encoding='utf-8-sig');known={line.split('\t')[0] for line in text.splitlines()}
added=['\t'.join(row[1:]) for row in rows if row[1] not in known]
if added:path.write_text(text.rstrip('\n')+'\n'+'\n'.join(added)+'\n',encoding='utf-8')
print(f'{len(rows)} localized infusion effects.')
