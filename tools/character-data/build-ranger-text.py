import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
rows = [line.split('\t') for filename in ('ranger-text.tsv', 'ranger-ui.tsv') for line in Path(__file__).with_name(filename).read_text(encoding='utf-8-sig').splitlines() if line]
quote = lambda value: json.dumps(value, ensure_ascii=False)
lines = ['// Generated by tools/character-data/build-ranger-text.py.', 'namespace Taruck.CharacterCreation {', '    public static class CharacterRangerText {', '        public static string Get(string id) { switch(id) {']
lines += ['            case ' + quote(key) + ': return ' + quote(ua) + ';' for key, ua, _, _ in rows]
lines += ['            default: throw new System.ArgumentException("Unknown Ranger feature: " + id);', '        } }', '    }', '}']
(root / 'Assets/Skripts/Domain/CharacterRangerText.cs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
localization = root / 'Assets/Resources/Localization.txt'
existing = localization.read_text(encoding='utf-8-sig')
known = {line.split('\t')[0] for line in existing.splitlines()}
new = []
for _, ua, en, ru in rows:
    for values in [(ua, en, ru), tuple(text.split(':')[0] for text in (ua, en, ru))]:
        if values[0] not in known:
            new.append('\t'.join(values)); known.add(values[0])
localization.write_text(existing.rstrip('\n') + '\n' + '\n'.join(new) + '\n', encoding='utf-8')
print(f'Generated {len(rows)} Ranger texts and {len(new)} translations.')
