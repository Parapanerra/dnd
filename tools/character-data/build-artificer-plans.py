"""Build only the level-gated infusion/plan choices; no artwork or item database."""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[2]
cache = Path(__file__).with_name('cache') / 'data'
classes = json.loads((cache / 'class/class-artificer.json').read_text(encoding='utf-8'))
optional = json.loads((cache / 'optionalfeatures.json').read_text(encoding='utf-8'))

def tables(value):
    if isinstance(value, dict):
        if value.get('type') == 'table':
            yield value
        for child in value.values():
            yield from tables(child)
    elif isinstance(value, list):
        for child in value:
            yield from tables(child)

rows = []
for feature in optional['optionalfeature']:
    if feature.get('source') != 'TCE' or 'AI' not in feature.get('featureType', []):
        continue
    if feature['name'] == 'Replicate Magic Item':
        for table in tables(feature):
            level = re.search(r'(\d+)', table.get('caption', ''))
            level = int(level.group(1)) if level else 2
            for row in table['rows']:
                match = re.search(r'\{@item ([^|}]+)', str(row[0]))
                if match:
                    rows.append((2014, level, 'replicate:' + match.group(1).lower(), match.group(1), False))
        continue
    prereq = feature.get('prerequisite', [{}])[0]
    level = prereq.get('level', {}).get('level', 2)
    rows.append((2014, level, feature['name'], feature['name'], False))

feature = next(f for f in classes['classFeature'] if f['name'] == 'Replicate Magic Item' and f['source'] == 'EFA')
for table in tables(feature):
    level = int(re.search(r'Level (\d+)', table['caption']).group(1))
    for row in table['rows']:
        match = re.search(r'\{@item ([^|}]+)', str(row[0]))
        if not match:
            continue  # Open categories need a separately named, player-specified item.
        name = match.group(1)
        armor = 'Armor' in name or name == 'Elven Chain'
        rows.append((2024, level, name, name, armor))

# The rules also permit open item categories. These choices require an explicit
# player-supplied item name; they never silently invent an item or its effects.
for slot in range(12):
    rows.append((2014, 2, f'custom.common:{slot}', 'Звичайний предмет — вручну', False))
    for level, kind, name in ((2, 'common', 'Звичайний предмет — вручну'),
                              (10, 'uncommon', 'Незвичайний дивопредмет — вручну'),
                              (14, 'rare', 'Рідкісний дивопредмет — вручну')):
        rows.append((2024, level, f'custom.{kind}:{slot}', name, False))

q = lambda value: json.dumps(value, ensure_ascii=False)
lines = [
    '// Generated by tools/character-data/build-artificer-plans.py.',
    'namespace Taruck.CharacterCreation {',
    '    public sealed class ArtificerPlanOption {',
    '        public readonly int edition, level; public readonly string id, name; public readonly bool armor;',
    '        public ArtificerPlanOption(int edition, int level, string id, string name, bool armor) { this.edition=edition; this.level=level; this.id=id; this.name=name; this.armor=armor; }',
    '    }',
    '    public static class CharacterArtificerPlans {',
    '        public static readonly System.Collections.Generic.IReadOnlyList<ArtificerPlanOption> All =',
    '            System.Array.AsReadOnly(new ArtificerPlanOption[] {',
]
for edition, level, key, name, armor in rows:
    lines.append(f'            new ArtificerPlanOption({edition}, {level}, {q(key)}, {q(name)}, {str(armor).lower()}),')
lines += ['        });', '        private static readonly string[,] Aliases = {']
for line in Path(__file__).with_name('artificer-plan-names.tsv').read_text(encoding='utf-8').splitlines():
    ua, en, ru = line.split('\t')
    for alias in (ua, en, ru):
        lines.append('            { ' + q(alias) + ', ' + q(en.lower()) + ' },')
lines += ['        };', '        internal static string CanonicalName(string value) {',
          '            value = (value ?? "").Trim();',
          '            for (int i=0; i<Aliases.GetLength(0); i++) if (string.Equals(value, Aliases[i,0], System.StringComparison.OrdinalIgnoreCase)) return Aliases[i,1];',
          '            return value.ToLowerInvariant();', '        }', '    }', '}']
(root / 'Assets/Skripts/Domain/CharacterArtificerPlans.cs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
localization = root / 'Assets/Resources/Localization.txt'
existing = localization.read_text(encoding='utf-8-sig')
known = {line.split('\t')[0] for line in existing.splitlines()}
added = []
for line in Path(__file__).with_name('artificer-plan-names.tsv').read_text(encoding='utf-8').splitlines():
    ua, en, ru = line.split('\t')
    if ua not in known:
        added.append(line)
        known.add(ua)
if added:
    localization.write_text(existing.rstrip('\n') + '\n' + '\n'.join(added) + '\n', encoding='utf-8')
print(f'Generated {len(rows)} plan records, including explicit manual-category choices; {len(added)} new translations.')
