from pathlib import Path
import json
root=Path(__file__).resolve().parents[2]
rows=[line.split('\t') for line in Path(__file__).with_name('warlock-text.tsv').read_text(encoding='utf-8-sig').splitlines() if line]
assert all(len(r)==4 for r in rows)
assert len({r[0] for r in rows})==len(rows)
q=lambda s:json.dumps(s,ensure_ascii=False)
code=['// Generated by tools/character-data/build-warlock-text.py.','namespace Taruck.CharacterCreation { public static class CharacterWarlockText { internal static string Get(string id) {switch(id){']+['case '+q(k)+': return '+q(ua)+';' for k,ua,en,ru in rows]+['default: throw new System.ArgumentException("Unknown Warlock text: "+id);}} public static readonly string[] Templates={'+','.join(q(ua) for k,ua,en,ru in rows if '{' in ua)+'};}}']
(root/'Assets/Skripts/Domain/CharacterWarlockText.cs').write_text('\n'.join(code)+'\n',encoding='utf-8')
p=root/'Assets/Resources/Localization.txt';existing=p.read_text(encoding='utf-8-sig');known={l.split('\t')[0] for l in existing.splitlines()};new=[]
for k,ua,en,ru in rows:
 for r in [(ua,en,ru),tuple(s.split(':')[0] for s in (ua,en,ru))]:
  if r[0] not in known: known.add(r[0]);new.append('\t'.join(r))
p.write_text(existing.rstrip('\n')+'\n'+'\n'.join(new)+'\n',encoding='utf-8')
print('Warlock texts:',len(rows),'new translations:',len(new))
