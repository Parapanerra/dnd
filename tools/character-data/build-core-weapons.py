aliases={en:(ua,ru) for en,ua,ru in (line.split('|') for line in names.splitlines())}
q=lambda s:json.dumps(s,ensure_ascii=False)
b=lambda v:str(bool(v)).lower()
lines=['// Generated by tools/character-data/build-core-weapons.py.','using System.Linq;','namespace Taruck.CharacterCreation {',
' public sealed class CoreWeapon { public readonly RulesEdition edition; public readonly string name,damage,mastery; public readonly bool simple,ranged,finesse,light,twoHanded; public CoreWeapon(RulesEdition e,string n,string d,string m,bool s,bool r,bool f,bool l,bool t){edition=e;name=n;damage=d;mastery=m;simple=s;ranged=r;finesse=f;light=l;twoHanded=t;} }',
' public static class CharacterWeaponCatalog { internal static readonly System.Collections.Generic.IReadOnlyList<CoreWeapon> All=System.Array.AsReadOnly(new CoreWeapon[]{']
for v in weapons:
    props={p.split('|')[0] if isinstance(p,str) else p['uid'].split('|')[0] for p in v.get('property',[])}
    mastery=next(iter(v.get('mastery',[])),'').split('|')[0].lower()
    lines.append('  new CoreWeapon(RulesEdition.Rules'+('2014' if v['source']=='PHB' else '2024')+','+','.join([q(aliases[v['name']][0]),q(v.get('dmg1','')),q(mastery),b(v['weaponCategory']=='simple'),b(v['type'].split('|')[0]=='R'),b('F' in props),b('L' in props),b('2H' in props)])+'),')
lines+=[' }); public static CoreWeapon Find(string name,RulesEdition edition)=>All.FirstOrDefault(w=>w.name==name&&w.edition==edition);',' } }']
(root/'Assets/Skripts/Domain/CharacterWeaponCatalog.cs').write_text('\n'.join(lines)+'\n',encoding='utf-8')
p=root/'Assets/Resources/Localization.txt';text=p.read_text(encoding='utf-8-sig');known={line.split('\t')[0] for line in text.splitlines()}
extra=['\t'.join((ua,en,ru)) for en,(ua,ru) in aliases.items() if ua not in known]
if extra:p.write_text(text.rstrip('\n')+'\n'+'\n'.join(extra)+'\n',encoding='utf-8')
print(f'Generated {len(weapons)} edition-specific core weapon records.')
