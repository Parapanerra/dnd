raw=urllib.request.urlopen(url,timeout=40).read()
weapons=[v for v in json.loads(raw)['baseitem'] if v.get('source') in ('PHB','XPHB') and v.get('weaponCategory') in ('simple','martial') and v.get('weapon')]
(root/'tools/character-data/cache/core-weapons.json').write_text(json.dumps({'source':url,'sha256':hashlib.sha256(raw).hexdigest(),'weapon':weapons},ensure_ascii=False,indent=2),encoding='utf-8')
