"""Localized summaries for every named plan in the existing TCE/EFA choices."""
import json
import re
from pathlib import Path

root=Path(__file__).resolve().parents[2]
folder=Path(__file__).parent
def rows(file):
    result={}
    for line in (folder/file).read_text(encoding='utf-8').splitlines():
        if not line:continue
        key,*text=line.split('\t')
        assert len(text)==3 and key not in result,(file,key)
        result[key]=text
    return result
common=rows('artificer-item-effects.tsv')
modern=rows('artificer-item-modern-effects.tsv')
base=rows('artificer-infusion-effects.tsv')
for key in ('Repeating Shot','Returning Weapon','Mind Sharpener','Boots of the Winding Path'):
    modern[key.lower()]=base[key]
for bonus in (1,2):
    common[f'+{bonus} shield']=[f'Щит: додатково +{bonus} КО понад його звичайний бонус +2, поки використовуєш.',f'Shield: additional +{bonus} AC beyond its normal +2 bonus while wielded.',f'Щит: дополнительно +{bonus} КД сверх обычного бонуса +2, пока используешь.']
    common[f'+{bonus} armor']=[f'Обладунок: +{bonus} КО понад базове значення обраного виду, поки носиш.',f'Armor: +{bonus} AC beyond the chosen type’s base while worn.',f'Доспех: +{bonus} КД сверх базы выбранного вида при ношении.']
    common[f'+{bonus} weapon']=[f'Магічна зброя: +{bonus} до атак і шкоди саме цим предметом.',f'Magic weapon: +{bonus} to attack and damage rolls with this specific weapon.',f'Магическое оружие: +{bonus} к атакам и урону именно этим предметом.']
    common[f'+{bonus} wand of the war mage']=[f'Поки тримаєш паличку: +{bonus} до атак заклинаннями; ігноруєш половинне укриття для цих атак. Не підвищує СК чи шкоду.',f'While holding the wand: +{bonus} to spell attack rolls; those attacks ignore Half Cover. Does not raise save DC or damage.',f'Пока держишь палочку: +{bonus} к атакам заклинаниями; эти атаки игнорируют укрытие наполовину. Не повышает Сл или урон.']
    common[f'+{bonus} wraps of unarmed power']=[f'Беззбройні удари: +{bonus} до атак і шкоди; шкода може бути силовою замість звичайного типу.',f'Unarmed Strikes: +{bonus} to attack and damage rolls; may deal Force instead of their normal damage type.',f'Безоружные удары: +{bonus} к атакам и урону; можно наносить силовой урон вместо обычного типа.']

reference=json.loads((folder/'cache/artificer-plan-items.json').read_text(encoding='utf-8'))
records=reference['item']+[dict(v['inherits'],name=v['name']) for v in reference['magicvariant']]
plans=re.findall(r'new ArtificerPlanOption\((\d+), \d+, "([^"]+)"', (root/'Assets/Skripts/Domain/CharacterArtificerPlans.cs').read_text(encoding='utf-8'))
selected={}
for edition,key in plans:
    if key.startswith('custom.') or edition=='2014' and key in base:continue
    name=key.removeprefix('replicate:').lower()
    texts=(modern if edition=='2024' and name in modern else common).get(name)
    assert texts,(edition,key,'Missing localized effect')
    texts=texts.copy()
    candidates=[v for v in records if v['name'].lower()==name and v.get('source') in (('EFA','XDMG') if edition=='2024' else ('DMG','ERLW','TCE'))]
    if name=='armor of resistance' or candidates and candidates[0].get('reqAttune'):
        for i,suffix in enumerate(('Потрібне налаштування.','Requires Attunement.','Требуется настройка.')):
            if suffix not in texts[i]:texts[i]+=' '+suffix
    selected[edition+':'+name]=texts
q=lambda s:json.dumps(s,ensure_ascii=False)
lines=['// Generated by tools/character-data/build-artificer-item-effects.py.','namespace Taruck.CharacterCreation { public static class CharacterArtificerItemEffects {',' public static string Get(string id, bool modern) {','  string key=(modern?"2024:":"2014:")+(id.StartsWith("replicate:",System.StringComparison.Ordinal)?id.Substring(10):id).ToLowerInvariant();','  switch(key) {']
lines+=['   case '+q(key)+': return '+q(text[0])+';' for key,text in selected.items()]
lines+=['   default: return "";','  }',' }','} }']
(root/'Assets/Skripts/Domain/CharacterArtificerItemEffects.cs').write_text('\n'.join(lines)+'\n',encoding='utf-8')
path=root/'Assets/Resources/Localization.txt';old=path.read_text(encoding='utf-8-sig');known={line.split('\t')[0] for line in old.splitlines()}
new=['\t'.join(text) for text in selected.values() if text[0] not in known]
new=list(dict.fromkeys(new))
if new:path.write_text(old.rstrip('\n')+'\n'+'\n'.join(new)+'\n',encoding='utf-8')
print(f'{len(selected)} named plan descriptions, all three languages, no missing named plan.')
