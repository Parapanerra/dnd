from pathlib import Path
import json

root = Path(__file__).resolve().parents[2]
rows = [line.split('|') for line in Path(__file__).with_name('wizard-progression.pipe').read_text(encoding='utf-8-sig').splitlines() if line]
assert all(len(row) == 4 for row in rows)
assert len({row[0] for row in rows}) == len(rows)
q = lambda text: json.dumps(text, ensure_ascii=False)
code = ['// Generated by build-wizard-progression.py.', 'namespace Taruck.CharacterCreation', '{', '    public static class CharacterWizardText', '    {', '        public static string Get(string key) => key switch', '        {']
code += ['            '+q(key)+' => '+q(ua)+',' for key, ua, _, _ in rows]
code += ['            _ => throw new System.ArgumentException("Unknown Wizard text: " + key)', '        };', '        public static readonly string[] Templates = { '+', '.join(q(ua) for _,ua,_,_ in rows if '{0}' in ua)+' };', '    }', '}']
(root / 'Assets/Skripts/Domain/CharacterWizardText.cs').write_text('\n'.join(code)+'\n',encoding='utf8')
path = root / 'Assets/Resources/Localization.txt'
existing = path.read_text(encoding='utf-8-sig')
known = {line.replace('\\t','\t').split('\t')[0] for line in existing.splitlines()}
new = ['\t'.join(row[1:]) for row in rows if row[1] not in known]
if new:
    path.write_text(existing.rstrip('\n')+'\n'+'\n'.join(new)+'\n', encoding='utf8')
