import json
from pathlib import Path
root=Path(__file__).resolve().parents[2]
rows=[line.split('\t') for line in Path(__file__).with_name('description-fixes.tsv').read_text(encoding='utf-8').splitlines() if line]
rows += [line.split('\t') for line in Path(__file__).with_name('species-description-fixes.tsv').read_text(encoding='utf-8').splitlines() if line]
assert all(len(row)==4 for row in rows)
q=lambda value:json.dumps(value,ensure_ascii=False)
lines=['// Generated by tools/character-data/build-description-fixes.py.',
       'namespace Taruck.CharacterCreation { public static class CharacterDescriptionText {',
       ' public static string Get(string id) { switch(id) {']
lines+=['  case '+q(key)+': return '+q(ua)+';' for key,ua,_,_ in rows]
lines+=['  default: throw new System.ArgumentException("Unknown description: " + id);',' } }',
        ' public static readonly string[] Templates = { '+', '.join(q(ua) for _,ua,_,_ in rows if '{' in ua)+' };',' } }']
(root/'Assets/Skripts/Domain/CharacterDescriptionText.cs').write_text('\n'.join(lines)+'\n',encoding='utf-8')
p=root/'Assets/Resources/Localization.txt';existing=p.read_text(encoding='utf-8-sig');known={line.split('\t')[0] for line in existing.splitlines()}
new=['\t'.join(row[1:]) for row in rows if row[1] not in known]
if new:p.write_text(existing.rstrip('\n')+'\n'+'\n'.join(new)+'\n',encoding='utf-8')
