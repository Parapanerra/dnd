import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
source = Path(__file__).parent
rows = []
for filename, prefix in [('fighter-text.tsv', ''), ('fighter-maneuvers.tsv', 'maneuver.')]:
    for line in (source / filename).read_text(encoding='utf-8-sig').splitlines():
        key, ua, en, ru = line.split('\t')
        rows.append((prefix + key, ua, en, ru))
quote = lambda value: json.dumps(value, ensure_ascii=False)
lines = ['// Generated by tools/character-data/build-fighter-text.py.', 'namespace Taruck.CharacterCreation {', '    public static class CharacterFighterText {', '        public static string Get(string id) { switch(id) {']
lines += ['            case ' + quote(key) + ': return ' + quote(ua) + ';' for key, ua, _, _ in rows]
lines += ['            default: throw new System.ArgumentException("Unknown Fighter feature: " + id);', '        } }', '    }', '    public static class CharacterFighterManeuvers {']
for edition in ('14', '24'):
    ids = [key[len('maneuver.'):-3] for key, _, _, _ in rows if key.startswith('maneuver.') and key.endswith('.' + edition)]
    lines.append('        private static readonly string[] List' + edition + ' = { ' + ', '.join(map(quote, ids)) + ' };')
lines += ['        public static string[] Options(CharacterCreationDraft d) => d.edition == RulesEdition.Rules2024 ? List24 : List14;', '        public static string Name(CharacterCreationDraft d, string id) => CharacterFighterText.Get("maneuver." + id + (d.edition == RulesEdition.Rules2024 ? ".24" : ".14")).Split(\':\')[0];', '    }', '}']
(root / 'Assets/Skripts/Domain/CharacterFighterText.cs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
localization = root / 'Assets/Resources/Localization.txt'
existing = localization.read_text(encoding='utf-8-sig')
known = {line.split('\t')[0] for line in existing.splitlines()}
new = []
for _, ua, en, ru in rows:
    for values in [(ua, en, ru), tuple(text.split(':')[0] for text in (ua, en, ru))]:
        if values[0] not in known:
            new.append('\t'.join(values))
            known.add(values[0])
localization.write_text(existing.rstrip('\n') + '\n' + '\n'.join(new) + '\n', encoding='utf-8')
print(f'Generated {len(rows)} Fighter texts and {len(new)} translations.')
