namespace Taruck.CharacterCreation
{
    internal static class CharacterClericSpellText
    {
        internal static string Effect(RulesEdition edition, string name)
        {
            bool modern = edition == RulesEdition.Rules2024;
            switch (name)
            {
                case "Burning Hands": return "У конусі 15 футів ряткидок Спритності: 3к6 вогняної шкоди, за успіху половина. Підпалює горючі речі, яких ніхто не носить.";
                case "Guiding Bolt": return "Далекобійна атака заклинанням: 4к6 променистої шкоди. Наступна атака по цілі до кінця твого наступного ходу має перевагу.";
                case "Inflict Wounds": return modern ? "Ряткидок Статури: 2к10 некротичної шкоди, за успіху половина." : "Ближня атака заклинанням: за влучання 3к10 некротичної шкоди.";
                case "Sacred Flame": return "Ряткидок Спритності або 1к8 променистої шкоди; ціль не отримує бонусів від укриття до цього ряткидка.";
                case "Sanctuary": return modern
                    ? "Атакувальник робить ряткидок Мудрості або мусить вибрати іншу ціль. Не захищає від ефектів площі. Атака, заклинання або шкода від захищеної істоти завершує ефект."
                    : "Атакувальник робить ряткидок Мудрості або мусить вибрати іншу ціль. Не захищає від ефектів площі. Атака, шкода або заклинання проти ворога від захищеної істоти завершує ефект.";
                case "Thaumaturgy": return modern
                    ? "Малі дива: гучний голос із перевагою на Залякування, зміна очей чи вогню, звуки, тремтіння землі, відкриття незамкнених дверей. До трьох ефектів одночасно."
                    : "Малі дива: гучний голос, зміна очей чи вогню, звуки, тремтіння землі, відкриття незамкнених дверей. До трьох ефектів одночасно.";
                case "Toll the Dead": return "Ряткидок Мудрості або 1к8 некротичної шкоди; якщо цілі бракує ОЗ, замість цього 1к12.";
                case "Word of Radiance": return "Вибрані видимі істоти в межах 5 футів роблять ряткидок Статури або отримують 1к6 променистої шкоди.";
                case "Command": return modern
                    ? "Ряткидок Мудрості або ціль наступного ходу виконує наказ: наблизитися, впустити, втекти, впасти долілиць або завмерти."
                    : "Ряткидок Мудрості або ціль наступного ходу виконує однослівний наказ. Не діє на нежить, на тих, хто не розуміє мови, або для прямо шкідливого наказу.";
                default: return "";
            }
        }
    }
}
