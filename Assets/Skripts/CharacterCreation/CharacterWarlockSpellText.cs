namespace Taruck.CharacterCreation
{
    internal static class CharacterWarlockSpellText
    {
        internal static string Effect(RulesEdition edition, string name)
        {
            switch (name)
            {
                case "Eldritch Blast": return "Далекобійна атака заклинанням: 1к10 силової шкоди.";
                case "Armor of Agathys": return edition == RulesEdition.Rules2024
                    ? "Отримуєш 5 тимчасових ОЗ. Ворог, що влучає по тобі ближньою атакою, отримує 5 холодової шкоди; ефект завершується, коли тимчасових ОЗ більше немає."
                    : "Отримуєш 5 тимчасових ОЗ. Ворог, що влучає по тобі ближньою атакою, поки зберігаються ці ОЗ, отримує 5 холодової шкоди.";
                case "Arms of Hadar": return "Істоти в межах 10 футів роблять ряткидок Сили: 2к6 некротичної шкоди й втрата реакцій до початку наступного ходу; за успіху лише половина шкоди.";
                case "Hellish Rebuke": return "Реакція на видиму істоту, яка завдала тобі шкоди: ряткидок Спритності проти 2к10 вогняної шкоди, за успіху половина.";
                case "Hex": return "Влучання кидком атаки по цілі завдають додатково 1к6 некротичної шкоди. Ціль має заваду на перевірки вибраної характеристики. Після її падіння до 0 ОЗ бонусною дією наступного ходу можна перенести прокляття.";
                default: return "";
            }
        }
    }
}
