namespace Taruck.CharacterCreation
{
    internal static class CharacterDruidSpellText
    {
        internal static string Effect(RulesEdition edition, string name)
        {
            bool modern = edition == RulesEdition.Rules2024;
            switch (name)
            {
                case "Druidcraft": return "Природні дрібні чари: прогноз погоди на добу, розквіт рослини, нешкідливий звук чи запах, запалення або гасіння малого вогню.";
                case "Elementalism": return "Дрібні ефекти повітря, землі, вогню чи води: подих вітру, пил, іскри, туман або чашка води; можна надати стихії просту форму.";
                case "Guidance": return modern
                    ? "Вибери навичку; істота додає 1к4 до всіх перевірок цієї навички протягом дії заклинання."
                    : "Істота додає 1к4 до однієї перевірки характеристики, після чого заклинання завершується.";
                case "Poison Spray": return modern
                    ? "Далекобійна атака заклинанням: за влучання 1к12 отруйної шкоди."
                    : "Ряткидок Статури або 1к12 отруйної шкоди.";
                case "Produce Flame": return modern
                    ? "Полум’я світить яскраво на 20 футів і тьмяно ще на 20. Дією можна атакувати заклинанням на 60 футів: 1к8 вогняної шкоди."
                    : "Полум’я світить яскраво на 10 футів і тьмяно ще на 10. Дією можна кинути його на 30 футів: атака заклинанням, 1к8 вогняної шкоди, після чого ефект завершується.";
                case "Resistance": return modern
                    ? "Вибери тип шкоди, крім психічної й силової. Раз за хід істота зменшує отриману шкоду цього типу на 1к4."
                    : "Істота додає 1к4 до одного ряткидка, після чого заклинання завершується.";
                case "Shillelagh": return modern
                    ? "Дубина або посох у твоїй руці використовує Мудрість для атак і шкоди, кістка шкоди 1к8. Можна завдавати силової шкоди; якщо відпустиш зброю, ефект завершується."
                    : "Дерев’яна дубина або посох використовує Мудрість для атак і шкоди; кістка шкоди 1к8, зброя магічна. Якщо відпустиш її, ефект завершується.";
                case "Spare the Dying": return "Істота з 0 ОЗ, яка ще жива, стає стабільною.";
                case "Thorn Whip": return "Ближня атака заклинанням: 1к6 колючої шкоди; ціль розміру Великий або менша можна підтягнути на 10 футів.";
                case "Create or Destroy Water": return "Створює або знищує до 10 галонів води у відкритій ємності. Натомість можна погасити відкритий вогонь дощем або прибрати туман у кубі 30 футів.";
                case "Ice Knife": return "Далекобійна атака заклинанням: 1к10 колючої шкоди. Влучить чи ні, уламок вибухає: ціль і істоти в межах 5 футів роблять ряткидок Спритності або отримують 2к6 холодової шкоди.";
                case "Detect Poison and Disease": return modern
                    ? "Відчуває й визначає отрути, отруйних істот і магічні хвороби в межах 30 футів."
                    : "Відчуває й визначає отрути, отруйних істот і хвороби в межах 30 футів.";
                default: return "";
            }
        }
    }
}
