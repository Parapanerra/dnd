using System;
using System.Collections.Generic;

namespace Taruck.CharacterCreation
{
    public static class CharacterMonkRules
    {
        public static int Points(CharacterCreationDraft d) => d.characterClass == "monk" && d.level >= 2 ? d.level : 0;
        public static int MartialFaces(CharacterCreationDraft d) => (d.level >= 17 ? 10 : d.level >= 11 ? 8 : d.level >= 5 ? 6 : 4) + (d.edition == RulesEdition.Rules2024 ? 2 : 0);
        public static string MartialDie(CharacterCreationDraft d) => "1d" + MartialFaces(d);
        internal static int MovementBonus(CharacterCreationDraft d) => d.level < 2 ? 0 : 10 + 5 * ((d.level - 2) / 4);
        public static bool AllSavingThrows(CharacterCreationDraft d) => d.characterClass == "monk" && d.level >= 14;
        public static string WeaponDamage(CharacterCreationDraft d, string weapon)
        {
            if (weapon == "Беззбройний удар") return MartialDie(d);
            string normal = CharacterCreationRules.MonkWeaponDamage(weapon);
            bool monkWeapon = weapon != "Легкий арбалет" && weapon != "Короткий лук" && weapon != "Дротик" && weapon != "Праща" &&
                (d.edition == RulesEdition.Rules2024 || weapon != "Велика дубина");
            if (monkWeapon && normal.StartsWith("1d", StringComparison.Ordinal) && int.TryParse(normal.Substring(2), out int faces) && faces < MartialFaces(d)) return MartialDie(d);
            return normal;
        }
        public static int WeaponModifier(CharacterCreationDraft d, int[] scores, string weapon)
        {
            int strength = CharacterCreationRules.Modifier(scores[0]);
            int dexterity = CharacterCreationRules.Modifier(scores[1]);
            if(weapon=="Дротик")return Math.Max(strength,dexterity);
            if (weapon == "Легкий арбалет" || weapon == "Короткий лук" || weapon == "Праща") return dexterity;
            if (d.edition == RulesEdition.Rules2014 && weapon == "Велика дубина") return strength;
            return Math.Max(strength, dexterity);
        }
        public static string AttackNotes(CharacterCreationDraft d) => d.edition == RulesEdition.Rules2024
            ? "Бойові мистецтва: беззбройний удар бонусною дією; без обладунку й щита, лише з монашою зброєю або без зброї."
            : "Бойові мистецтва: після дії Атака монашою зброєю чи без зброї — беззбройний удар бонусною дією; без обладунку й щита.";

        internal static string Features(CharacterCreationDraft d)
        {
            bool modern = d.edition == RulesEdition.Rules2024;
            var lines = new List<string> {
                "Захист без обладунку: КО 10 + модифікатори Спритності та Мудрості.",
                string.Format(CharacterDescriptionText.Get("monk.die"), MartialDie(d)),
                CharacterDescriptionText.Get(modern ? "monk.martial24" : "monk.martial14")
            };
            if (d.level >= 2)
            {
                lines.Add("Рух без обладунку: без обладунку й щита швидкість зростає на 10 футів. Бонус становить 15 футів із 6 рівня, 20 із 10, 25 із 14 та 30 із 18 рівня Монаха.");
                if (modern)
                    lines.Add("Зосередженість монаха: запас очок дорівнює рівню Монаха. Усі витрачені очки повертаються після короткого або довгого відпочинку. СК здібностей = 8 + БМ + модифікатор Мудрості.");
                lines.Add(modern && d.level >= 10 ? "Шквал ударів: 1 очко ци — три беззбройні удари бонусною дією." : modern
                    ? "Шквал ударів: 1 очко ци — два беззбройні удари бонусною дією."
                    : "Шквал ударів: після дії Атака витрать 1 очко ци на два беззбройні удари бонусною дією.");
                lines.Add(modern
                    ? "Терплячий захист: Відхід бонусною дією; за 1 очко ци — Відхід та Ухиляння разом."
                    : "Терплячий захист: за 1 очко ци виконай Ухиляння бонусною дією.");
                lines.Add(modern
                    ? "Крок вітру: Ривок бонусною дією; за 1 очко ци — Ривок і Відхід разом та подвоєна дальність стрибка на цей хід."
                    : "Крок вітру: за 1 очко ци виконай Ривок або Відхід бонусною дією; дальність стрибка подвоюється на цей хід.");
                if (modern) lines.Add("Незвичайний метаболізм: при ініціативі віднови всі очки ци та ОЗ у кількості рівень монаха + кістка бойових мистецтв; раз за довгий відпочинок.");
                else lines.Add("Відновлення ци: короткий або довгий відпочинок із щонайменше 30 хвилинами медитації.");
            }
            if (d.level >= 3)
            {
                lines.Add(modern && d.level >= 13 ? "Відбиття енергії: реакцією зменш шкоду атаки будь-якого типу на 1к10 + модифікатор Спритності + рівень монаха." : modern
                    ? "Відбиття атак: реакцією зменш шкоду атаки з дробильною, колючою чи рубаною складовою на 1к10 + Спритність + рівень монаха."
                    : "Відбиття снарядів: реакцією зменш шкоду дальньої атаки зброєю на 1к10 + Спритність + рівень монаха.");
                lines.Add(modern
                    ? "Перенаправлення: якщо шкода стала 0, за 1 очко ци обери видиму ціль у 5 футах для ближньої атаки або в 60 футах без повного укриття для дальньої. Ряткидок Спритності; провал — дві кістки бойових мистецтв + модифікатор Спритності шкоди того самого типу."
                    : "Повернення снаряда: якщо шкода стала 0 й одна рука вільна, спіймай достатньо малий снаряд; за 1 очко ци атакуй ним цією ж реакцією, дальність 20/60 футів, із майстерністю.");
                if (d.subclass == "openhand") lines.Add(modern
                    ? "Відкрита долоня: влучання Шквалом ударів — збити з ніг (ряткидок Спритності), відштовхнути на 15 футів (Сила) або заборонити провоковані атаки до початку наступного ходу цілі."
                    : "Відкрита долоня: влучання Шквалом ударів — збити з ніг (ряткидок Спритності), відштовхнути на 15 футів (Сила) або заборонити реакції до кінця твого наступного ходу.");
            }
            if (d.level >= 4) lines.Add("Повільне падіння: реакцією зменш шкоду від падіння на 5 × рівень монаха.");
            if (d.level >= 5)
            {
                lines.Add("Додаткова атака: дві атаки замість однієї при дії Атака.");
                lines.Add(modern
                    ? "Приголомшливий удар: раз за хід після влучання монашою зброєю або без зброї витрать 1 очко ци. Статура: провал — Приголомшений до початку твого наступного ходу; успіх — половина швидкості та перевага наступної атаки по цілі до того часу."
                    : "Приголомшливий удар: після влучання ближньою атакою зброєю витрать 1 очко ци; провал ряткидка Статури — Приголомшений до кінця твого наступного ходу.");
            }
            if (d.level >= 6)
            {
                lines.Add(modern ? "Посилені удари: беззбройний удар може завдавати силової шкоди замість звичайної." : "Удари, посилені ци: беззбройні удари магічні для подолання опору й імунітету.");
                if (d.subclass == "openhand") lines.Add(modern
                    ? "Цілісність тіла: бонусною дією віднови ОЗ за кісткою бойових мистецтв + Мудрість (мінімум 1); використань за модифікатором Мудрості, мінімум 1, за довгий відпочинок."
                    : "Цілісність тіла: дією віднови 3 × рівень монаха ОЗ; раз за довгий відпочинок.");
            }
            if (d.level >= 7)
            {
                lines.Add(modern
                    ? "Уникнення: ряткидок Спритності проти половини шкоди — 0 при успіху, половина при провалі; не діє в Недієздатному стані."
                    : "Уникнення: ряткидок Спритності проти половини шкоди — 0 при успіху, половина при провалі.");
                if (!modern) lines.Add("Спокій розуму: дією заверши один ефект Зачарований або Наляканий на собі.");
            }
            if (d.level >= 9) lines.Add("Акробатичний рух: без обладунку й щита пересувайся вертикальними поверхнями та водою, не падаючи під час руху.");
            if (d.level >= 10)
            {
                if (modern)
                {
                    lines.Add("Поглиблена зосередженість: Терплячий захист за очко ци також дає дві кістки бойових мистецтв тимчасових ОЗ. Крок вітру за очко ци може перемістити з тобою охочу істоту в 5 футах розміру Великий або менше без провокованих атак по ній.");
                    lines.Add("Самовідновлення: наприкінці кожного свого ходу заверши один стан Зачарований, Наляканий або Отруєний; відсутність їжі й води не дає виснаження.");
                }
                else lines.Add("Чистота тіла: імунітет до хвороб та отрути.");
            }
            if (d.level >= 11 && d.subclass == "openhand") lines.Add(modern
                ? "Стрімкий крок: одразу після іншої бонусної дії можеш також використати Крок вітру."
                : "Умиротворення: після довгого відпочинку Святилище на собі до наступного довгого відпочинку; СК за Мудрістю, стандартні умови дострокового завершення.");
            if (d.level >= 13 && !modern) lines.Add("Мова сонця й місяця: розумієш усі усні мови; кожна істота, яка розуміє хоч одну мову, розуміє тебе.");
            if (d.level >= 14) lines.Add("Досконалі ряткидки: володіння всіма ряткидками; після провалу за 1 очко ци перекинь і використай новий результат.");
            if (d.level >= 15) lines.Add(modern
                ? "Досконала зосередженість: при ініціативі без Незвичайного метаболізму доведи залишок очок ци до 4, якщо їх було менше."
                : "Нестаріюче тіло: немає слабкості старості та магічного старіння; їжа й вода більше не потрібні, природна смерть від старості можлива.");
            if (d.level >= 17 && d.subclass == "openhand") lines.Add(modern
                ? "Тремтлива долоня: влучання без зброї, 4 очки ци — вібрації на кількість днів за рівнем монаха, одна ціль. На тій самій площині дією або замість однієї атаки заверши: Статура проти 10к12 силової шкоди, успіх — половина. Можна скасувати без шкоди."
                : "Тремтлива долоня: влучання без зброї, 3 очки ци — вібрації на кількість днів за рівнем монаха, одна ціль. На тій самій площині дією заверши: провал Статури — 0 ОЗ, успіх — 10к10 некротичної шкоди. Можна скасувати без шкоди.");
            if (d.level >= 18) lines.Add(modern
                ? "Вища оборона: на початку ходу витрать 3 очки ци на опір усій шкоді, крім силової, на 1 хвилину або до Недієздатності."
                : "Порожнє тіло: дією витрать 4 очки ци — Невидимість і опір усій шкоді, крім силової, на 1 хвилину. За 8 очок ци — Астральна проєкція лише для себе, без матеріальних компонентів.");
            if (d.level >= 20) lines.Add(modern
                ? "Тіло й розум: Спритність та Мудрість +4, максимум 25; уже враховано в характеристиках."
                : "Досконалість: при ініціативі, якщо ци немає, віднови 4 очки.");
            return string.Join("\n", lines);
        }
    }
}
